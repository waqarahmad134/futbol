// Day index since the shared epoch, matches the daily rotation used elsewhere.
export function getDayIndex(date: Date = new Date()): number {
  const epoch = new Date(2024, 0, 1).getTime();
  const today = new Date(date.getFullYear(), date.getMonth(), date.getDate()).getTime();
  return Math.floor((today - epoch) / 86400000);
}

export function getDailyWrestler(date: Date = new Date()): Wrestler {
  return WRESTLERS[getDayIndex(date) % WRESTLERS.length];
}

export function findWrestler(name: string): Wrestler | undefined {
  return WRESTLERS.find((w) => w.name.toLowerCase() === name.trim().toLowerCase());
}
